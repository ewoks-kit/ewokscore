from functools import lru_cache
from typing import Dict
from typing import Type
from typing import Union

from .._conda import CondaManager
from .._conda import CondaRequirements
from .._pip_venv import PipVenvManager
from .._pip_venv import PipVenvRequirements
from .._pixi import PixiManager
from .._pixi import PixiRequirements
from .._poetry import PoetryManager
from .._poetry import PoetryRequirements
from .._uv import UvManager
from .._uv import UvRequirements
from .base_manager import BaseManager

Requirements = Union[
    PipVenvRequirements,
    UvRequirements,
    PoetryRequirements,
    CondaRequirements,
    PixiRequirements,
]
"""Requirements generated by any of the supported package managers."""


@lru_cache(1)
def get_supported_managers() -> Dict[str, Type[BaseManager]]:
    managers = [
        PipVenvManager,
        UvManager,
        PoetryManager,
        CondaManager,
        PixiManager,
    ]
    return {manager_cls.NAME: manager_cls for manager_cls in managers}
